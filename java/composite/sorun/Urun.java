package composite.sorun;

public class Urun {

    private final String ad;
    private final int gram;

    public Urun(String ad, int gram) {
        this.ad = ad;
        this.gram = gram;
    }

    public String getAd() {
        return ad;
    }

    public int getGram() {
        return gram;
    }
}
